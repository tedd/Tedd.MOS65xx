using System.Text;
using Tedd.MOS65xx.Emulator.Media;
using Tedd.MOS65xx.Emulator.Tools;

namespace Tedd.MOS65xx.Web.Demo;

/// <summary>
/// The built-in tech demo: a self-contained machine code program that is assembled at runtime with
/// <see cref="Assembler"/> and injected through <c>EmulatorSession.AttachProgram</c>.
///
/// <para>What it does (all driven by one raster interrupt per frame, no KERNAL/BASIC code involved once it
/// runs, so it works with OpenROMs as well as the original ROMs):</para>
/// <list type="bullet">
/// <item>Banks out BASIC and KERNAL ($01 = $35), installs its own IRQ/NMI vectors in RAM and disables the
/// CIA timer interrupts, so the demo owns the machine and runs forever until reset.</item>
/// <item>Raster colour bars: the IRQ handler waits for every raster line of the display area and writes a
/// colour from a 256-entry table to $D020/$D021; the table offset advances every frame so the bars move.</item>
/// <item>A hardware-scrolled text scroller on the bottom text row (XSCROLL + 38 column mode switched in the
/// right border of the line above it).</item>
/// <item>Four sprites moving on Lissajous paths (sine tables, 9-bit X positions).</item>
/// <item>A three voice SID tune: bass (sawtooth, percussive envelope), a fast arpeggio (pulse) and a lead
/// (pulse), sequenced at 50 Hz with 6 frames per step over a four chord progression.</item>
/// </list>
/// </summary>
public static class DemoProgram
{
    /// <summary>Load address of the generated PRG (BASIC start, so it can also be saved and RUN normally).</summary>
    public const ushort LoadAddress = 0x0801;

    private const int SpriteBlock = 0x0840 / 64;           // sprite data at $0840 (64-byte block 33)
    private const int CodeStart = 0x0880;
    private const int ScrollRow = 0x07C0;                  // screen row 24
    private const string ScrollText =
        "   TEDD.MOS65XX - A CYCLE-EXACT COMMODORE 64 EMULATOR WRITTEN IN C#. " +
        "THIS DEMO WAS ASSEMBLED IN YOUR BROWSER A MOMENT AGO AND IS RUNNING ON THE EMULATED 6510: " +
        "RASTER INTERRUPTS, COLOUR BARS, HARDWARE SCROLLING, SPRITES AND A THREE VOICE SID TUNE. " +
        "THE VIC-II, CIA AND SID ARE MODELLED PER CYCLE; THE 6502 CORE IS VERIFIED AGAINST 2.56 MILLION " +
        "SINGLESTEPTESTS VECTORS. PRESS RESET TO RETURN TO BASIC.   ";

    /// <summary>Assembles the demo and returns it as a PRG file (2-byte load address header + data).</summary>
    public static byte[] BuildPrg()
    {
        var result = Assembler.Assemble(Source(), LoadAddress);
        if (result.Origin != LoadAddress || result.Labels["start"] != CodeStart)
            throw new InvalidOperationException("Demo layout mismatch: the BASIC stub SYS address does not match the code start");
        return new PrgFile(result.Origin, result.Bytes).ToBytes();
    }

