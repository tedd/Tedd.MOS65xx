    private static IEnumerable<(int Row, int Col, int Colour, string Text)> TitleLines()
    {
        yield return (2, 14, 7, "TEDD.MOS65XX");
        yield return (4, 5, 1, "CYCLE-EXACT COMMODORE 64 IN C#");
        yield return (6, 2, 15, "6510 + VIC-II + CIA + SID, PER CYCLE");
        yield return (8, 1, 15, "RUNNING IN YOUR BROWSER (BLAZOR WASM)");
        yield return (20, 4, 13, "RASTER IRQ - SPRITES - SID MUSIC");
        yield return (22, 8, 12, "PRESS RESET TO EXIT DEMO");
    }

    /// <summary>ASCII (upper case) to C64 screen codes for the upper-case/graphics character set.</summary>
    public static byte[] ScreenCodes(string text)
    {
        var bytes = new byte[text.Length];
        for (int i = 0; i < text.Length; i++)
        {
            char c = char.ToUpperInvariant(text[i]);
            bytes[i] = c switch
            {
                >= 'A' and <= 'Z' => (byte)(c - 'A' + 1),
                '@' => 0,
                '[' => 27,
                ']' => 29,
                >= ' ' and <= '?' => (byte)c,
                _ => 32,
            };
        }
        return bytes;
    }

    private static byte[] BallSprite()
    {
        // 24x21 hires sprite: a filled circle with a small highlight
        var data = new byte[63];
        const double cx = 11.5, cy = 10.0, r = 9.5;
        for (int y = 0; y < 21; y++)
        {
            for (int x = 0; x < 24; x++)
            {
                double dx = x - cx, dy = y - cy;
                bool on = dx * dx + dy * dy <= r * r;
                double hx = x - 8.5, hy = y - 6.5;
                if (hx * hx + hy * hy <= 4.0) on = false; // highlight hole
                if (on) data[y * 3 + x / 8] |= (byte)(0x80 >> (x & 7));
            }
        }
        return data;
    }

    private static byte[] BarTable()
    {
        // four 32-line bars (16 lines of colour ramp + 16 lines black) = 256 entries
        int[][] ramps =
        {
            new[] { 6, 6, 4, 4, 14, 14, 3, 3, 3, 3, 14, 14, 4, 4, 6, 6 },      // blue
            new[] { 2, 2, 8, 8, 10, 10, 7, 7, 7, 7, 10, 10, 8, 8, 2, 2 },      // red
            new[] { 9, 9, 5, 5, 13, 13, 1, 1, 1, 1, 13, 13, 5, 5, 9, 9 },      // green
            new[] { 11, 11, 12, 12, 15, 15, 1, 1, 1, 1, 15, 15, 12, 12, 11, 11 }, // grey
        };
        var table = new byte[256];
        int o = 0;
        foreach (var ramp in ramps)
        {
            foreach (var c in ramp) table[o++] = (byte)c;
            o += 16;
        }
        return table;
    }

    private static (byte[] XLo, byte[] XHi, byte[] Y) SineTables()
    {
        var xlo = new byte[256];
        var xhi = new byte[256];
        var y = new byte[256];
        for (int i = 0; i < 256; i++)
        {
            double s = (Math.Sin(i * Math.PI * 2 / 256) + 1) / 2;
            int x = 24 + (int)Math.Round(s * 296);   // 24..320: fully visible sprite X range
            xlo[i] = (byte)x;
            xhi[i] = (byte)(x >> 8);
            y[i] = (byte)(50 + (int)Math.Round(s * 168));  // 50..218: keeps sprites off lines 241/242 (scroller timing)
        }
        return (xlo, xhi, y);
    }

    private static (byte[] Lo, byte[] Hi) FrequencyTables()
    {
        // SID frequency register for MIDI notes 0..95 (PAL clock)
        var lo = new byte[96];
        var hi = new byte[96];
        for (int n = 0; n < 96; n++)
        {
            double f = 440.0 * Math.Pow(2, (n - 69) / 12.0);
            int v = (int)Math.Round(f * 16777216.0 / 985248.0);
            if (v > 0xFFFF) v = 0xFFFF;
            lo[n] = (byte)v;
            hi[n] = (byte)(v >> 8);
        }
        return (lo, hi);
    }

    private static string Bytes(byte[] data)
    {
        var sb = new StringBuilder();
        for (int i = 0; i < data.Length; i += 16)
        {
            sb.AppendLine();
            sb.Append("        .byte ");
            sb.Append(string.Join(",", data.Skip(i).Take(16).Select(b => "$" + b.ToString("x2"))));
        }
        return sb.ToString();
    }
